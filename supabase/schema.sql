-- Basic server-side sanity checks prevent impossible client snapshots from
-- being written even though gameplay remains offline-first.
create or replace function public.validate_game_progress()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  d jsonb := new.data;
  lvl bigint := coalesce((d->>'qgame_level')::bigint, 1);
  noor bigint := coalesce((d->>'qgame_noor')::bigint, 0);
  xp bigint := coalesce((d->>'qgame_score')::bigint, 0);
  total bigint := coalesce((d->>'qgame_total')::bigint, 0);
  correct bigint := coalesce((d->>'qgame_correct')::bigint, 0);
  wrong bigint := coalesce((d->>'qgame_wrong')::bigint, 0);
  combo bigint := coalesce((d->>'qgame_combo')::bigint, 0);
  best_combo bigint := coalesce((d->>'qgame_best_combo')::bigint, 0);
  streak bigint := coalesce((d->>'qgame_streak')::bigint, 0);
  longest bigint := coalesce((d->>'qgame_longest_streak')::bigint, 0);
begin
  if lvl < 1 or lvl > 100
     or noor < 0 or noor > 10000000
     or xp < 0 or xp > 100000000
     or total < 0 or total > 1000000
     or correct < 0 or wrong < 0
     or correct + wrong > total
     or combo < 0 or combo > 100000
     or best_combo < combo
     or streak < 0 or streak > 36500
     or longest < streak or longest > 36500 then
    raise exception 'Invalid game progress snapshot';
  end if;
  return new;
end;
$$;

drop trigger if exists game_progress_validate on public.game_progress;
create trigger game_progress_validate
before insert or update on public.game_progress
for each row execute function public.validate_game_progress();
